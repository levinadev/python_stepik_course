"""
Даны три списка:
names = ["Анна", "Иван", "Мария"],
ages = [25, 30, 28],
cities = ["Москва", "Казань", "Сочи"].

Используя zip(), выведите в формате:
"Имя: {name}, Возраст: {age}, Город: {city}".
"""

names = ["Анна", "Иван", "Мария"]
ages = [25, 30, 28]
cities = ["Москва", "Казань", "Сочи"]

for name, age, city in zip(names, ages, cities):
    print(f"Имя: {name}, Возраст: {age}, Город: {city}")