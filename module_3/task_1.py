"""
📝 Итоговый проект: Анализ текста
Условие:
Напишите программу, которая анализирует введённый текст и выводит статистику по нему.

Программа должна:
Считывать строку текста.
Выводить количество слов в тексте.
Выводить самое длинное слово.
Выводить количество уникальных слов (с помощью множества).
Проверять, все ли слова длиннее 3 символов — выводить True или False.
Проверять, есть ли в тексте слово, начинающееся с буквы "а" — выводить True или False.

Требования:
Используйте try-except для обработки пустого ввода.
Используйте lambda, map() или filter() для обработки списка слов.
Используйте any() и all() для проверок.
Используйте множества для подсчёта уникальных слов.
Используйте модуль string для удаления знаков препинания.

Ввод:
На вход подаётся строка с текстом (например: яблоко банан апельсин груша апельсин).

Вывод:
Пять строк:
Количество слов.
Самое длинное слово.
Количество уникальных слов.
Все ли слова длиннее 3 символов (True/False).
Есть ли слово на "а" (True/False).
"""

try:
    text = input()
    words = text.split()

    if not words:
        print("Ошибка: пустой ввод")
    else:
        # 1. Количество слов
        print(len(words))

        # 2. Самое длинное слово
        print(max(words, key=len))

        # 3. Количество уникальных слов
        print(len(set(words)))

        # 4. Все ли слова длиннее 3 символов
        print(all(len(word) > 3 for word in words))

except:
    print("Ошибка: пустой ввод")