"""
Дан список words = ["кот", "собака", "попугай", "хомяк"] и строка search = "попугай".
Напишите программу, которая находит индекс элемента search в списке.
Если элемент найден, выведите "Найдено на позиции {index}", иначе выведите "Не найдено".
Используйте цикл с enumerate() для поиска.
"""

words = ["кот", "собака", "попугай", "хомяк"]
search = "попугай"
found = False
for i, word in enumerate(words):
    if word == search:
        print(f"Найдено на позиции {i}")
        found = True
        break
if not found:
    print("Не найдено")