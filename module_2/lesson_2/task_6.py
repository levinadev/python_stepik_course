"""
Напишите программу, которая считывает целое число n.
С помощью вложенных циклов выведите таблицу умножения для всех чисел от 1 до n.
Формат вывода каждой строки:
i * j = результат

Подсказка: чтобы цикл прошёл от 1 до n включительно, вспомните, что верхняя граница range() не входит в диапазон.
"""

n = int(input())
for i in range(1, n + 1):
    for j in range(1, n + 1):
        print(f"{i} * {j} = {i * j}")